from pathlib import Path
from typing import Dict
import shutil

from fastapi import FastAPI, File, HTTPException, UploadFile
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import StreamingResponse
from pydantic import BaseModel, Field

from backend.agent.agent import get_agent
from backend.api.chain import RagChat, clear_llm_cache, source_label
from backend.core.config import settings
from backend.ingestion.ingestion import ingest_file

app = FastAPI(
    title="RAG Document Chat API",
    description="REST backend for RAG document question answering and ingestion.",
    version="1.0.0",
)

# Enable CORS for frontend clients
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

# In-memory store of conversation sessions: session_id -> RagChat instance
sessions: Dict[str, RagChat] = {}


def get_or_create_session(session_id: str) -> RagChat:
    """Retrieve existing chat instance or create a new one for this session."""
    if session_id not in sessions:
        sessions[session_id] = RagChat()
    return sessions[session_id]


# --- Request & Response Models ---

class ChatRequest(BaseModel):
    question: str = Field(..., description="The user's query about the documents")
    session_id: str = Field(default="default", description="Unique session identifier for chat history")


class SourceDocument(BaseModel):
    label: str
    text: str


class ChatResponse(BaseModel):
    answer: str
    standalone: str
    sources: list[SourceDocument]


class ResetRequest(BaseModel):
    session_id: str = Field(default="default", description="Session identifier to clear")


class DocumentInfo(BaseModel):
    filename: str
    size_bytes: int


# --- API Endpoints ---

